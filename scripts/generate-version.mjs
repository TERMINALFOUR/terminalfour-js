// Generates src/generated-version.ts from package.json so the SDK version is
// baked in at build time. Reading the version at runtime (walking up to find
// package.json) fails when the SDK is bundled into another app, producing a
// `Terminalfour-JS-SDK/unknown` User-Agent (issue #38). Baking it in means the
// version is always present regardless of how the SDK is consumed.
//
// Run from the package root (npm prebuild/pretest/prepare). The emitted file is
// gitignored — it is a build artifact, not source.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = dirname(scriptDir);

const packageJsonPath = join(packageRoot, 'package.json');
const outputPath = join(packageRoot, 'src', 'generated-version.ts');

const pkg = JSON.parse(readFileSync(packageJsonPath, 'utf8'));

if (typeof pkg.version !== 'string' || pkg.version.length === 0) {
  throw new Error(`Cannot read a valid "version" from ${packageJsonPath}`);
}

const contents = `// AUTO-GENERATED by scripts/generate-version.mjs — do not edit by hand.
// Baked in at build time from package.json so the SDK version is always present
// in the User-Agent, even when the SDK is bundled. See issue #38.
export const SDK_VERSION = '${pkg.version}';
`;

writeFileSync(outputPath, contents, 'utf8');

console.log(`Wrote SDK version ${pkg.version} to ${outputPath}`);
